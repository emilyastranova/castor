// Generates src/lib/m3/tokens.css: Material 3 color roles for light and dark from a seed.
// Usage: node scripts/gen-tokens.mjs [#seed]
import { readFileSync, writeFileSync } from 'node:fs';
import {
	Hct,
	SchemeTonalSpot,
	MaterialDynamicColors,
	argbFromHex,
	hexFromArgb,
	customColor
} from '@material/material-color-utilities';

const seed = process.argv[2] ?? '#4f5bd5';
const roles = [
	'primary', 'onPrimary', 'primaryContainer', 'onPrimaryContainer',
	'secondary', 'onSecondary', 'secondaryContainer', 'onSecondaryContainer',
	'tertiary', 'onTertiary', 'tertiaryContainer', 'onTertiaryContainer',
	'error', 'onError', 'errorContainer', 'onErrorContainer',
	'surface', 'onSurface', 'surfaceVariant', 'onSurfaceVariant',
	'surfaceDim', 'surfaceBright', 'surfaceContainerLowest', 'surfaceContainerLow',
	'surfaceContainer', 'surfaceContainerHigh', 'surfaceContainerHighest',
	'inverseSurface', 'inverseOnSurface', 'inversePrimary',
	'outline', 'outlineVariant', 'shadow', 'scrim', 'surfaceTint',
	'primaryFixed', 'primaryFixedDim', 'onPrimaryFixed', 'onPrimaryFixedVariant',
	'secondaryFixed', 'secondaryFixedDim', 'onSecondaryFixed', 'onSecondaryFixedVariant',
	'tertiaryFixed', 'tertiaryFixedDim', 'onTertiaryFixed', 'onTertiaryFixedVariant',
	'background', 'onBackground'
];
const kebab = (s) => s.replace(/[A-Z]/g, (c) => '-' + c.toLowerCase());

// Extra hues (status colours etc.) as M3 custom colours. Not blended towards the seed:
// harmonising pulled blue and violet into the same lavender, and status hues must stay distinct.
const customColors = JSON.parse(
	readFileSync(new URL('../src/lib/m3/custom-colors.json', import.meta.url), 'utf8')
);

function customBlock(isDark) {
	const lines = [];
	for (const [name, hex] of Object.entries(customColors)) {
		const group = customColor(argbFromHex(seed), { name, value: argbFromHex(hex), blend: false });
		const g = isDark ? group.dark : group.light;
		lines.push(`\t--md-custom-color-${name}: ${hexFromArgb(g.color)};`);
		lines.push(`\t--md-custom-color-on-${name}: ${hexFromArgb(g.onColor)};`);
		lines.push(`\t--md-custom-color-${name}-container: ${hexFromArgb(g.colorContainer)};`);
		lines.push(`\t--md-custom-color-on-${name}-container: ${hexFromArgb(g.onColorContainer)};`);
	}
	return lines.join('\n');
}

function block(isDark) {
	const scheme = new SchemeTonalSpot(Hct.fromInt(argbFromHex(seed)), isDark, 0);
	return (
		roles
			.map((r) => `\t--md-sys-color-${kebab(r)}: ${hexFromArgb(MaterialDynamicColors[r].getArgb(scheme))};`)
			.join('\n') +
		'\n' +
		customBlock(isDark)
	);
}

const css = `/* Generated by scripts/gen-tokens.mjs from seed ${seed}. Do not edit by hand. */
:root, :root[data-theme='light'] {
\tcolor-scheme: light;
${block(false)}
}
:root[data-theme='dark'] {
\tcolor-scheme: dark;
${block(true)}
}
@media (prefers-color-scheme: dark) {
\t:root:not([data-theme='light']) {
\t\tcolor-scheme: dark;
${block(true).replace(/^\t/gm, '\t\t')}
\t}
}
`;
writeFileSync(new URL('../src/lib/m3/tokens.css', import.meta.url), css);
console.log('wrote src/lib/m3/tokens.css for seed', seed);
